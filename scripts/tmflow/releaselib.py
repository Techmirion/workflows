"""Decisions of the `release-pr`, `release` and `sync-dev` workflows (git.md 9 and 14).

Pure functions over facts that the caller gathers (git ancestry, tags, PRs), so
every rule can be tested without git or GitHub.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field

from . import fmt

SYNC_TITLE = "chore(release): sync main into dev"
GENERATED_MARK = "<!-- generated by Techmirion/workflows release-pr -->"
REVERTS_RE = re.compile(r"\bReverts\s+(?:[A-Za-z0-9][A-Za-z0-9-]*/[A-Za-z0-9._-]+)?#(?P<n>[0-9]+)\b")


class Refused(Exception):
    """The workflow must not act. `reasons` says why, in plain words."""

    def __init__(self, reasons):
        self.reasons = list(reasons)
        super().__init__("; ".join(self.reasons))


def is_sync_pr(pr: dict) -> bool:
    return (pr.get("head") == "main" or (pr.get("head") or "").endswith("/main")) and pr.get("base") == "dev"


def is_release_pr(pr: dict) -> bool:
    return pr.get("head") == "dev" and pr.get("base") == "main"


# --- release-pr -------------------------------------------------------------

@dataclass
class Entry:
    number: int | None
    title: str
    head: str | None
    body: str = ""
    sha: str = ""
    reverts: list = field(default_factory=list)
    reverted_by: list = field(default_factory=list)


def collect_entries(merges: list[dict], prs: dict) -> tuple[list[Entry], list[str]]:
    """Turn the first-parent commits of `main..dev` into release entries.

    `prs` maps PR number to the PR (title, body, head) as the forge knows it.
    The sync PR (head `main`) is not an entry: what it brings is already released.
    """
    entries, warnings = [], []
    for m in merges:
        n = m.get("number")
        if n is None:
            what = "merge" if m.get("merge") else "commit"
            warnings.append(f"{what} {m['sha'][:7]} reached dev without a pull request (`{m['subject']}`): listed, check it")
            entries.append(Entry(None, m["subject"], None, "", m["sha"]))
            continue
        pr = prs.get(n) or {}
        head = pr.get("head") or (m.get("head") or "").split("/", 1)[-1]
        if head == "main":
            continue
        e = Entry(n, pr.get("title") or m.get("body") or m["subject"], head, pr.get("body") or "", m["sha"])
        e.reverts = [int(x.group("n")) for x in REVERTS_RE.finditer(e.body)]
        entries.append(e)
    by_number = {e.number: e for e in entries if e.number is not None}
    for e in entries:
        for r in e.reverts:
            if r in by_number:
                by_number[r].reverted_by.append(e.number)
    return entries, warnings


def _active(e: Entry, by_number: dict, seen=None) -> bool:
    """A PR is active unless an active PR in the same release reverts it."""
    seen = seen or set()
    if e.number in seen:
        return True
    seen = seen | {e.number}
    return not any(_active(by_number[r], by_number, seen) for r in e.reverted_by if r in by_number)


def completed_issues(entries: list[Entry]) -> list[str]:
    by_number = {e.number: e for e in entries if e.number is not None}
    seen, out = set(), []
    for e in entries:
        if e.number is None or e.reverts or not _active(e, by_number):
            continue
        for ref in fmt.closing_refs(e.body):
            if ref not in seen:
                seen.add(ref)
                out.append(ref)
    return out


def release_list(entries: list[Entry]) -> str:
    """The generated part of the body: PRs, then one `Fixes` line per completed issue."""
    by_number = {e.number: e for e in entries if e.number is not None}
    lines = ["## Pull requests in this release", ""]
    if not entries:
        lines.append("- (none)")
    for e in entries:
        if e.number is None:
            lines.append(f"- {e.sha[:7]} {e.title} (not a pull request)")
            continue
        note = ""
        if e.reverts:
            note = " (reverts " + ", ".join(f"#{r}" for r in e.reverts) + ")"
        elif not _active(e, by_number):
            note = " (reverted by " + ", ".join(f"#{r}" for r in e.reverted_by) + ")"
        lines.append(f"- #{e.number} {e.title}{note}")
    issues = completed_issues(entries)
    lines += ["", "## Issues completed", ""]
    lines += [f"Fixes {ref}" for ref in issues] or ["(none)"]
    return "\n".join(lines)


def plan_release_pr(*, version: str, summary: str, tags: list[str], main_sha: str, dev_sha: str,
                    main_is_ancestor_of_dev: bool, entries: list[Entry], open_release_prs: list[dict]) -> dict:
    """Title and body of the release PR, or Refused with every reason that applies."""
    reasons = []
    v = fmt.parse_version(version)
    if v is None:
        reasons.append(f"`{version}` is not a version: use vMAJOR.MINOR.PATCH, for example v1.4.0")
    if not main_is_ancestor_of_dev:
        reasons.append("main is not an ancestor of dev: a hotfix has not been synced back. "
                       f"Merge the `{SYNC_TITLE}` PR into dev first")
    if main_sha == dev_sha or (main_is_ancestor_of_dev and not entries):
        reasons.append("dev has nothing that main does not have: nothing to release")
    existing = fmt.release_tags(tags)
    if v is not None and existing and v <= existing[-1]:
        reasons.append(f"{fmt.format_version(v)} is not above the last release tag {fmt.format_version(existing[-1])}")
    if open_release_prs:
        reasons.append("a release PR is already open: " + ", ".join(f"#{p['number']}" for p in open_release_prs))
    if reasons:
        raise Refused(reasons)
    tag = fmt.format_version(v)
    summary = " ".join((summary or "").split())
    title = f"release: {tag} {summary}" if summary else f"release: {tag}"
    body = "\n".join([
        f"Version: {tag}",
        "",
        "Approve only after looking at staging: this PR ships all of `dev`.",
        "",
        GENERATED_MARK,
        release_list(entries),
        "",
    ])
    return {"version": tag, "title": title, "body": body}


# --- release (push to main) -------------------------------------------------

def release_notes(pr: dict, kind: str) -> str:
    if kind == "release":
        lines = [ln for ln in (pr.get("body") or "").splitlines()
                 if not fmt.VERSION_LINE_RE.match(ln) and ln.strip() != GENERATED_MARK
                 and not ln.startswith("Approve only after looking at staging")]
        text = "\n".join(lines).strip()
        return text + f"\n\nRelease PR: #{pr['number']}\n"
    refs = fmt.closing_refs(pr.get("body") or "")
    lines = [f"Hotfix: {pr['title']} (#{pr['number']})", ""] + [f"Fixes {r}" for r in refs]
    return "\n".join(lines).strip() + "\n"


def plan_release(*, sha: str, prs: list[dict], tags: list[str], tags_at_sha: list[str], release_exists,
                 sha_is_ancestor_of_dev: bool, dev_is_ancestor_of_sha: bool, open_sync_prs: list[dict],
                 move_major_tag: bool = False) -> dict:
    """What to do after a push to main.

    Returns {"kind", "version", "actions": [...], "warnings": [...]}. Actions, in order:
    ("tag", tag, message) ("release", tag, name, body) ("move-tag", major, sha)
    ("fast-forward-dev", sha) ("sync-pr", title, body). Raises Refused on errors.
    """
    warnings: list[str] = []
    merged = [p for p in prs if p.get("merged") and p.get("merge_commit_sha") == sha and p.get("base") == "main"]
    if not merged:
        return {"kind": "none", "version": None, "actions": [], "warnings": [
            f"{sha[:7]} reached main without a merged pull request: not tagged and not synced. "
            "This bypassed the flow: tell the admins and undo it with a revert PR (git.md 9)"]}
    pr = merged[0]
    head = pr.get("head") or ""
    if head == "dev":
        kind = "release"
    elif head.startswith("hotfix/"):
        kind = "hotfix"
    else:
        return {"kind": "none", "version": None, "actions": [], "warnings": [
            f"PR #{pr['number']} ({head} -> main) is neither a release PR (head dev) nor a hotfix "
            "(head hotfix/*): not tagged and not synced, handle it by hand"]}

    here = [t for t in tags_at_sha if fmt.TAG_RE.match(t)]
    others = [t for t in tags if fmt.TAG_RE.match(t) and t not in here]
    last = fmt.release_tags(others)
    if here:
        version = fmt.parse_version(sorted(here, key=fmt.parse_version)[-1])
        tag_needed = False
    elif kind == "release":
        version = fmt.version_from_body(pr.get("body") or "")
        if version is None:
            raise Refused([f"release PR #{pr['number']} has no `Version: vX.Y.Z` line in its body"])
        tag_needed = True
    else:
        version = fmt.next_patch(others)
        if not last:
            warnings.append("no release tag yet: the hotfix is tagged v0.0.1")
        tag_needed = True
    tag = fmt.format_version(version)
    if tag_needed and last and version <= last[-1]:
        raise Refused([f"{tag} is not above the last release tag {fmt.format_version(last[-1])}"])
    if tag_needed and tag in tags:
        raise Refused([f"tag {tag} already exists on another commit; tags are never moved"])

    actions = []
    if tag_needed:
        actions.append(("tag", tag, f"{tag}\n\n{pr['title']} (#{pr['number']})"))
    if not release_exists(tag):
        name = tag
        if kind == "release":
            m = fmt.RELEASE_TITLE_RE.match(pr.get("title") or "")
            if m and m.group("summary"):
                name = f"{tag} {m.group('summary')}"
        else:
            name = f"{tag} (hotfix)"
        actions.append(("release", tag, name, release_notes(pr, kind)))
    if move_major_tag:
        actions.append(("move-tag", f"v{version[0]}", sha))
    sync_actions, sync_warnings = plan_sync(
        sha=sha, sha_is_ancestor_of_dev=sha_is_ancestor_of_dev, dev_is_ancestor_of_sha=dev_is_ancestor_of_sha,
        open_sync_prs=open_sync_prs, body=sync_body(tag, pr))
    actions += sync_actions
    warnings += sync_warnings
    return {"kind": kind, "version": tag, "pr": pr["number"], "actions": actions, "warnings": warnings}


def plan_sync(*, sha: str, sha_is_ancestor_of_dev: bool, dev_is_ancestor_of_sha: bool,
              open_sync_prs: list[dict], body: str, dev_exists: bool = True) -> tuple[list, list[str]]:
    """Bring `main` (at `sha`) back into `dev`. Used by `release` and by `sync-dev`.

    Returns (actions, warnings); actions are ("fast-forward-dev", sha) or
    ("sync-pr", title, body), or none when dev already contains main.
    """
    if not dev_exists:
        return [], ["there is no `dev` branch: nothing to sync"]
    if sha_is_ancestor_of_dev:
        return [], []  # dev already contains main
    if dev_is_ancestor_of_sha:
        return [("fast-forward-dev", sha)], []
    if open_sync_prs:
        return [], ["dev has moved; a sync PR is already open: " + ", ".join(f"#{p['number']}" for p in open_sync_prs)]
    return [("sync-pr", SYNC_TITLE, body)], []


def sync_body(tag: str, pr: dict) -> str:
    return (
        f"Brings `main` ({tag}, PR #{pr['number']}) back into `dev`, because `dev` moved on while "
        "the release was being merged.\n\nMerge it with a merge commit like any other PR "
        "(git.md 9). Until it is merged, `release-pr` refuses to start the next release.\n\n"
        "- [x] No issue needed\n"
    )


def sync_dev_body(sha: str, pr: dict | None) -> str:
    """Body of the sync PR opened by `sync-dev` (a push to main outside the release flow)."""
    what = f"PR #{pr['number']}" if pr else "a push without a pull request"
    return (
        f"Brings `main` ({sha[:7]}, {what}) back into `dev`, because `dev` has commits that `main` "
        "does not have, so it cannot simply be fast-forwarded.\n\nMerge it with a merge commit like any "
        "other PR (git.md 9).\n\n- [x] No issue needed\n"
    )


# --- cleanup ----------------------------------------------------------------

NEVER_DELETE = ("dev", "main")


def plan_cleanup(*, merged: bool, head: str, head_repo: str | None, base_repo: str | None,
                 default_branch: str, protected=(), branch_sha: str | None, pr_head_sha: str | None,
                 other_open_prs: int = 0) -> tuple[bool, str]:
    """Delete the head branch of a merged PR? Returns (delete, reason)."""
    keep = set(NEVER_DELETE) | set(protected) | {default_branch}
    if not merged:
        return False, "the PR was closed without merging"
    if head in keep:
        return False, f"`{head}` is never deleted"
    if not head_repo or head_repo != base_repo:
        return False, "the branch lives in a fork"
    if branch_sha is None:
        return False, f"`{head}` is already gone"
    if pr_head_sha and branch_sha != pr_head_sha:
        return False, f"`{head}` has commits that were not merged ({branch_sha[:7]} != {pr_head_sha[:7]})"
    if other_open_prs:
        return False, f"`{head}` is the head of another open PR"
    return True, f"`{head}` was merged"
